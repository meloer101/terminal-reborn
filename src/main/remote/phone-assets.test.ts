// What the iPhone app (ios/, PRD F22) takes from the desktop instead of keeping its own copy: status words, agent names
// and marks, the lucide icons it uses (the desktop's set, CLAUDE.md), the words of generated branch names and the
// link's limits. This test writes them into ios/ from the
// shared modules and fails when the files there differ, so the Swift app cannot drift;
// `WAVI_WRITE_PHONE_ASSETS=1 npx vitest run src/main/remote/phone-assets.test.ts` writes them after a change here.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import * as lucide from 'lucide-react'
import { createElement, type ComponentType } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, it } from 'vitest'
import { AGENT_ICON_SVG } from '../../shared/agent-icon-svg'
import { agentName, CLI_AGENTS } from '../../shared/agents'
import { ADJECTIVES, NOUNS } from '../../shared/new-session'
import { DEFAULT_REMOTE_PORT, PAIRING_ALPHABET, PAIRING_CODE_LENGTH, REMOTE_LIMITS, REMOTE_PROTOCOL } from '../../shared/remote'
import { STATUS_LABEL } from '../../shared/session-status'

const IOS = join(__dirname, '../../../ios/Wavi')
const SHARED = join(IOS, 'Resources/Shared.json')
const MARKS = join(IOS, 'Assets.xcassets/Agents')
const ICONS = join(IOS, 'Assets.xcassets/Lucide')
/** The lucide icons the app draws, by asset name (`Image("Lucide/git-branch")`). */
const LUCIDE: Record<string, keyof typeof lucide> = {
  'arrow-up': 'ArrowUp',
  bot: 'Bot',
  camera: 'Camera',
  check: 'Check',
  'chevron-down': 'ChevronDown',
  'chevron-left': 'ChevronLeft',
  'chevron-right': 'ChevronRight',
  file: 'File',
  'git-branch': 'GitBranch',
  'git-pull-request': 'GitPullRequest',
  image: 'Image',
  plus: 'Plus',
  smartphone: 'Smartphone',
  square: 'Square',
  'square-check': 'SquareCheck',
  'square-terminal': 'SquareTerminal',
  'triangle-alert': 'TriangleAlert',
  x: 'X'
}
const WRITE = process.env.WAVI_WRITE_PHONE_ASSETS === '1'
const TOKENS = join(__dirname, '../../renderer/styles/tokens.css')
/** The colours that mean something (status, diff): the phone reads them from Shared.json so the two apps agree. */
const MEANING_TOKENS = ['status-working', 'status-attention', 'status-attention-bg', 'status-done', 'status-error', 'status-idle', 'diff-add-fg', 'diff-add-bg', 'diff-del-fg', 'diff-del-bg']

/** `--name: #rrggbb[aa]` from the dark (`:root[data-theme='dark']`) and light (`:root[data-theme='light']`) blocks of tokens.css. */
function meaningColors(): Record<string, { dark: string; light: string }> {
  const css = readFileSync(TOKENS, 'utf8')
  const block = (theme: 'dark' | 'light'): string => {
    const start = css.indexOf(`:root[data-theme='${theme}'] {`)
    if (start < 0) throw new Error(`tokens.css has no ${theme} block`)
    return css.slice(start, css.indexOf('}', start))
  }
  const value = (text: string, name: string): string => {
    const found = new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?);`).exec(text)
    if (!found) throw new Error(`tokens.css has no --${name}`)
    return found[1]!.toLowerCase()
  }
  const dark = block('dark')
  const light = block('light')
  return Object.fromEntries(MEANING_TOKENS.map((name) => [name, { dark: value(dark, name), light: value(light, name) }]))
}

function shared(): string {
  const value = {
    note: 'Generated by src/main/remote/phone-assets.test.ts from src/shared. Do not edit.',
    colors: meaningColors(),
    statusLabel: STATUS_LABEL,
    agents: [...CLI_AGENTS.map((id) => ({ id, name: agentName(id), mark: AGENT_ICON_SVG[id] !== undefined })), { id: 'shell', name: agentName('shell'), mark: false }],
    branchWords: { adjectives: ADJECTIVES, nouns: NOUNS },
    limits: REMOTE_LIMITS,
    pairing: { alphabet: PAIRING_ALPHABET, length: PAIRING_CODE_LENGTH, defaultPort: DEFAULT_REMOTE_PORT },
    protocol: REMOTE_PROTOCOL
  }
  return JSON.stringify(value, null, 2) + '\n'
}

/** One imageset per SVG, drawn as a template so it takes the colour of the text around it (Figma 34K). */
function imagesets(svgs: Record<string, string>): Record<string, string> {
  const files: Record<string, string> = {
    'Contents.json': JSON.stringify({ info: { author: 'xcode', version: 1 }, properties: { 'provides-namespace': true } }, null, 2) + '\n'
  }
  for (const [id, svg] of Object.entries(svgs)) {
    files[`${id}.imageset/${id}.svg`] = svg.replaceAll('currentColor', '#000000') + '\n'
    files[`${id}.imageset/Contents.json`] =
      JSON.stringify(
        {
          images: [{ filename: `${id}.svg`, idiom: 'universal' }],
          info: { author: 'xcode', version: 1 },
          properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' }
        },
        null,
        2
      ) + '\n'
  }
  return files
}

/**
 * Path data spelled out for iOS's SVG reader (CoreSVG), which draws pieces of a mark wrongly otherwise: arc flags
 * written flush with the next number (`a6 6 0 013 4` is flags 0, 1 then x 3) get separators, and the root's
 * `fill-rule` is repeated on every path, which does not inherit it there.
 */
function forCoreSvg(svg: string): string {
  const rule = /<svg[^>]*\sfill-rule="([a-z]+)"/.exec(svg)?.[1]
  return svg.replace(/<path\b([^>]*?)\sd="([^"]*)"/g, (_whole, attrs: string, d: string) => {
    const withRule = rule && !/fill-rule=/.test(attrs) ? `${attrs} fill-rule="${rule}"` : attrs
    return `<path${withRule} d="${spellPath(d)}"`
  })
}

function spellPath(d: string): string {
  const number = /^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?/
  const out: string[] = []
  let command = ''
  let param = 0
  let i = 0
  while (i < d.length) {
    const ch = d[i]!
    if (/[\s,]/.test(ch)) {
      i++
    } else if (/[a-zA-Z]/.test(ch)) {
      command = ch
      param = 0
      out.push(ch)
      i++
    } else if ((command === 'a' || command === 'A') && (param % 7 === 3 || param % 7 === 4)) {
      out.push(ch)
      param++
      i++
    } else {
      const found = number.exec(d.slice(i))
      if (!found) throw new Error(`unreadable path data at ${i}: ${d.slice(i, i + 20)}`)
      out.push(found[0])
      param++
      i += found[0].length
    }
  }
  return out.join(' ')
}

const marks = () => imagesets(Object.fromEntries(Object.entries(AGENT_ICON_SVG).filter((e): e is [string, string] => e[1] !== undefined).map(([id, svg]) => [id, forCoreSvg(svg)])))

/** At the desktop's stroke (CLAUDE.md: 1.75), without lucide's class and aria attributes. */
const icons = () =>
  imagesets(
    Object.fromEntries(
      Object.entries(LUCIDE).map(([name, component]) => [
        name,
        renderToStaticMarkup(createElement(lucide[component] as ComponentType<{ size: number; strokeWidth: number }>, { size: 24, strokeWidth: 1.75 }))
          .replace(/ class="[^"]*"/, '')
          .replace(/ aria-hidden="true"/, '')
      ])
    )
  )

function sync(dir: string, want: Record<string, string>): void {
  if (WRITE) {
    rmSync(dir, { recursive: true, force: true })
    for (const [path, text] of Object.entries(want)) {
      mkdirSync(join(dir, path, '..'), { recursive: true })
      writeFileSync(join(dir, path), text)
    }
  }
  expect(listed(dir).sort()).toEqual(Object.keys(want).sort())
  for (const [path, text] of Object.entries(want)) expect(readFileSync(join(dir, path), 'utf8')).toBe(text)
}

const listed = (dir: string, prefix = ''): string[] =>
  existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? listed(join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`])) : []

describe('the iPhone app’s copy of src/shared', () => {
  it('ios/Wavi/Resources/Shared.json', () => {
    if (WRITE) writeFileSync(SHARED, shared())
    expect(readFileSync(SHARED, 'utf8')).toBe(shared())
  })

  it('ios/Wavi/Assets.xcassets/Agents', () => sync(MARKS, marks()))

  it('ios/Wavi/Assets.xcassets/Lucide', () => sync(ICONS, icons()))
})
