// Fixed inputs and outputs of the phone link's cryptography (PRD F22, crypto.ts), for the iPhone app's Swift port to
// check itself against byte by byte (ios/WaviTests/CryptoTests.swift). This test recomputes them with the Mac's own
// functions, so the file cannot drift from the Mac; `WAVI_WRITE_VECTORS=1 npx vitest run src/main/remote/vectors.test.ts`
// writes it after a deliberate protocol change.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createPrivateKey } from 'node:crypto'
import { ristretto255, x25519 } from '@noble/curves/ed25519.js'
import { describe, expect, it } from 'vitest'
import { authProof, b64u, FrameCipher, hkdf, PAKE_INFO, pairingKey, pakeBase, pakeReply, seal, sessionKeys, sharedSecret } from './crypto'

const FILE = join(__dirname, '../../shared/remote-vectors.json')
const bytes = (start: number, length: number) => Uint8Array.from({ length }, (_, i) => (start + i * 7) % 256)
const hex = (b: Uint8Array) => Buffer.from(b).toString('hex')
const scalar = (seed: number) => {
  // A fixed scalar below the group order: 31 bytes of pattern, little-endian, top byte 0.
  let n = 0n
  const b = bytes(seed, 31)
  for (let i = b.length - 1; i >= 0; i--) n = (n << 8n) | BigInt(b[i]!)
  return n % ristretto255.Point.Fn.ORDER
}
const leHex = (n: bigint) => {
  const out = new Uint8Array(32)
  for (let i = 0, v = n; i < 32; i++, v >>= 8n) out[i] = Number(v & 0xffn)
  return hex(out)
}

function compute() {
  const code = 'K7QX3M'
  const phoneSecret = bytes(1, 32)
  const macSecret = bytes(100, 32)
  const phonePublic = b64u(x25519.getPublicKey(phoneSecret))
  const macPublic = b64u(x25519.getPublicKey(macSecret))
  const macKey = createPrivateKey({ key: { kty: 'OKP', crv: 'X25519', d: b64u(macSecret), x: macPublic }, format: 'jwk' })

  const x = scalar(3)
  const y = scalar(50)
  const base = pakeBase(code)
  const a = base.multiply(x).toBytes()
  const reply = pakeReply(code, b64u(a), macPublic, y)!
  const pakeKey = hkdf(base.multiply((x * y) % ristretto255.Point.Fn.ORDER).toBytes(), Buffer.concat([a, Buffer.from(reply.b, 'base64url')]), PAKE_INFO)

  const secret = bytes(200, 32)
  const serverNonce = bytes(10, 16)
  const clientNonce = bytes(20, 16)
  const keys = sessionKeys(secret, serverNonce, clientNonce)
  const frames = new FrameCipher(keys.fromPhone, keys.toPhone)
  const frame0 = frames.seal({ id: 1, type: 'snapshot' })
  const frame1 = frames.seal({ id: 2, type: 'send', session: 's1', text: '你好' })

  return {
    note: 'Generated by src/main/remote/vectors.test.ts from the Mac crypto (src/main/remote/crypto.ts). Bytes are hex unless named b64u.',
    x25519: {
      phoneSecret: hex(phoneSecret),
      macSecret: hex(macSecret),
      phonePublicB64u: phonePublic,
      macPublicB64u: macPublic,
      shared: hex(sharedSecret(macKey, phonePublic)!),
      code,
      pairingKey: hex(pairingKey(macKey, phonePublic, code)!)
    },
    seal: [0, 1, 2 ** 40 + 5].map((counter) => {
      const key = bytes(77, 32)
      const plaintext = '{"name":"iPhone 17"}'
      return { key: hex(key), counter, plaintext, sealed: hex(seal(key, counter, Buffer.from(plaintext, 'utf8'))) }
    }),
    pake: {
      code,
      dst: PAKE_INFO,
      base: hex(base.toBytes()),
      x: leHex(x),
      a: hex(a),
      y: leHex(y),
      bB64u: reply.b,
      key: hex(pakeKey),
      boxB64u: reply.box,
      macPublicB64u: macPublic
    },
    session: {
      secret: hex(secret),
      serverNonce: hex(serverNonce),
      clientNonce: hex(clientNonce),
      proof: hex(authProof(secret, serverNonce, clientNonce)),
      fromPhone: hex(keys.fromPhone),
      toPhone: hex(keys.toPhone),
      frames: [hex(frame0), hex(frame1)],
      framePlaintexts: ['{"id":1,"type":"snapshot"}', '{"id":2,"type":"send","session":"s1","text":"你好"}']
    }
  }
}

describe('phone link test vectors', () => {
  it('src/shared/remote-vectors.json is what the Mac computes', () => {
    const now = JSON.stringify(compute(), null, 2) + '\n'
    if (process.env.WAVI_WRITE_VECTORS === '1') writeFileSync(FILE, now)
    expect(readFileSync(FILE, 'utf8')).toBe(now)
  })
})
