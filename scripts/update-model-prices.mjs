#!/usr/bin/env node
// Writes src/shared/model-prices.data.ts (设置 · 额度's "API 等价", PRD F11) from LiteLLM's public price table (MIT,
// https://github.com/BerriAI/litellm). Only the direct providers of the agents Wavi reads are kept, in USD per million
// tokens. The file is generated: change this script and run it, never edit it by hand.
//   node scripts/update-model-prices.mjs [path-or-url]
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json'
const OUT = fileURLToPath(new URL('../src/shared/model-prices.data.ts', import.meta.url))
/** Bare keys from these providers. */
const PROVIDERS = new Set(['anthropic', 'openai', 'gemini', 'deepseek'])
/** Prefixed keys whose bare name an agent's log uses. */
const PREFIXES = ['xai/', 'gemini/', 'deepseek/', 'moonshot/', 'dashscope/', 'zai/']
const MODES = new Set(['chat', 'responses'])

const arg = process.argv[2] ?? SOURCE
const text = /^https?:/.test(arg) ? await (await fetch(arg)).text() : await readFile(arg, 'utf8')
const table = JSON.parse(text)
const perMillion = (v) => (typeof v === 'number' ? Math.round(v * 1e6 * 10_000) / 10_000 : undefined)
const out = {}
// Bare keys first: a provider's own entry wins over a reseller's prefixed one of the same name.
const entries = Object.entries(table).sort(([a], [b]) => Number(a.includes('/')) - Number(b.includes('/')))
for (const [key, v] of entries) {
  if (!v || typeof v !== 'object' || typeof v.input_cost_per_token !== 'number' || !MODES.has(v.mode)) continue
  let name = null
  if (!key.includes('/') && PROVIDERS.has(v.litellm_provider)) name = key
  else {
    const prefix = PREFIXES.find((p) => key.startsWith(p))
    if (prefix && !key.slice(prefix.length).includes('/')) name = key.slice(prefix.length)
  }
  if (!name || out[name]) continue
  const price = { input: perMillion(v.input_cost_per_token), output: perMillion(v.output_cost_per_token) }
  const read = perMillion(v.cache_read_input_token_cost)
  const write = perMillion(v.cache_creation_input_token_cost)
  if (read !== undefined) price.cacheRead = read
  if (write !== undefined) price.cacheWrite = write
  out[name] = price
}
const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]))
const header = `// Generated by scripts/update-model-prices.mjs from LiteLLM (MIT) ${SOURCE}, fetched ${new Date().toISOString().slice(0, 10)}. Do not edit.\n`
const body = Object.entries(sorted)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')}`)
  .join(',\n')
await writeFile(OUT, `${header}export const MODEL_PRICES: Readonly<Record<string, { input: number; output: number; cacheRead?: number; cacheWrite?: number }>> = {\n${body}\n}\n`)
console.log(`${Object.keys(sorted).length} models → ${OUT}`)
